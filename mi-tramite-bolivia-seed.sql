    tramite_version_id  BIGINT NOT NULL REFERENCES tramite_version(id) ON DELETE CASCADE,
    modalidad_id        BIGINT REFERENCES modalidad_tramite(id) ON DELETE CASCADE,
    numero              SMALLINT NOT NULL CHECK (numero > 0),
    titulo              VARCHAR(220) NOT NULL,
    descripcion         TEXT NOT NULL,
    lugar               VARCHAR(180),
    url_accion          TEXT,
    es_fuera_sistema    BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (tramite_version_id, modalidad_id, numero)
);

CREATE TABLE costo_tramite (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_version_id  BIGINT NOT NULL REFERENCES tramite_version(id) ON DELETE CASCADE,
    modalidad_id        BIGINT REFERENCES modalidad_tramite(id) ON DELETE CASCADE,
    concepto            VARCHAR(180) NOT NULL,
    moneda              CHAR(3) NOT NULL DEFAULT 'BOB',
    monto               NUMERIC(12,2) CHECK (monto >= 0),
    monto_desde         NUMERIC(12,2) CHECK (monto_desde >= 0),
    monto_hasta         NUMERIC(12,2) CHECK (monto_hasta >= 0),
    es_gratuito         BOOLEAN NOT NULL DEFAULT FALSE,
    periodicidad        VARCHAR(50),
    medio_pago          VARCHAR(180),
    instrucciones       TEXT,
    aplica_si           JSONB NOT NULL DEFAULT '{}'::jsonb,
    verificado_en       TIMESTAMPTZ,
    CHECK (jsonb_typeof(aplica_si) = 'object'),
    CHECK (
        es_gratuito
        OR monto IS NOT NULL
        OR (monto_desde IS NOT NULL AND monto_hasta IS NOT NULL)
    ),
    CHECK (monto_hasta IS NULL OR monto_desde IS NULL OR monto_hasta >= monto_desde)
);

