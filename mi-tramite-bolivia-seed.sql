CREATE VIEW vw_tramite_publicado AS
SELECT
    t.id,
    t.codigo,
    t.slug,
    t.institucion_id,
    i.nombre AS institucion,
    i.sigla,
    t.categoria_id,
    c.nombre AS categoria,
    v.id AS version_id,
    v.numero_version,
    v.titulo,
    v.resumen,
    v.descripcion,
    v.publico_objetivo,
    v.resultado_esperado,
    v.advertencias,
    v.plazo_texto,
    v.vigencia_resultado_texto,
    v.requiere_cita,
    v.url_inicio,
    v.verificado_en,
    v.proxima_revision_en,
    v.publicado_en
FROM tramite t
JOIN institucion i ON i.id = t.institucion_id
LEFT JOIN categoria c ON c.id = t.categoria_id
JOIN tramite_version v ON v.tramite_id = t.id
WHERE t.estado = 'activo'
  AND i.estado = 'activa'
  AND v.estado_editorial = 'publicada'
  AND (v.valido_desde IS NULL OR v.valido_desde <= NOW())
  AND (v.valido_hasta IS NULL OR v.valido_hasta > NOW());

