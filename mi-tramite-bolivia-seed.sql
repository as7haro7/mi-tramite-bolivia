-- -----------------------------------------------------------------------------
-- ARCHIVOS MULTIMEDIA
-- Neon conserva metadatos; los binarios viven en object storage externo.
-- Una variante apunta al archivo original mediante original_id.
-- -----------------------------------------------------------------------------
CREATE TABLE archivo_multimedia (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    original_id         UUID REFERENCES archivo_multimedia(id) ON DELETE CASCADE,
    variante            VARCHAR(30) NOT NULL DEFAULT 'original'
                        CHECK (variante IN ('original', 'miniatura', 'pequena',
                                            'mediana', 'grande')),
    proveedor           VARCHAR(30) NOT NULL
                        CHECK (proveedor IN ('s3', 'r2', 'cloudinary', 'otro')),
    contenedor          VARCHAR(120) NOT NULL,
    clave_objeto        TEXT NOT NULL,
    url_publica         TEXT,
    mime_type           VARCHAR(80) NOT NULL
                        CHECK (mime_type IN ('image/svg+xml', 'image/png',
                                             'image/jpeg', 'image/webp')),
    tamano_bytes        BIGINT NOT NULL CHECK (tamano_bytes > 0),
    ancho_px            INTEGER CHECK (ancho_px > 0),
    alto_px             INTEGER CHECK (alto_px > 0),
    sha256              CHAR(64) NOT NULL,
    texto_alternativo   VARCHAR(250) NOT NULL,
    estado              VARCHAR(20) NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente', 'activo', 'rechazado',
                                          'eliminado')),
    creado_por          BIGINT,
    creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (proveedor, contenedor, clave_objeto),
    CHECK (
        (variante = 'original' AND original_id IS NULL)
        OR (variante <> 'original' AND original_id IS NOT NULL)
    ),
    CHECK (
        (ancho_px IS NULL AND alto_px IS NULL)
        OR (ancho_px IS NOT NULL AND alto_px IS NOT NULL)
    ),
    CHECK (sha256 ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX uq_archivo_variante
    ON archivo_multimedia(original_id, variante)
    WHERE original_id IS NOT NULL;

