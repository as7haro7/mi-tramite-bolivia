-- ADVERTENCIA:
--   Este archivo es un RESET DE DESARROLLO. Elimina las tablas v1 y v2.
--   No debe ejecutarse sobre producción. Para producción se deben crear
--   migraciones versionadas (por ejemplo, con golang-migrate o Goose).
--
-- PRINCIPIOS DEL MODELO:
--   1. Un trámite no contiene dirección, horario ni costo como texto libre.
--   2. Lo publicado es una versión editorial aprobada e inmutable.
--   3. Toda afirmación publicada puede vincularse con una fuente oficial.
--   4. El scraping crea candidatos; nunca publica automáticamente.
--   5. Los embeddings pertenecen a fragmentos de una versión, no al trámite.
--   6. No se almacenan identificadores de dispositivo en texto claro.
-- =============================================================================

