CREATE OR REPLACE FUNCTION proteger_version_publicada()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.estado_editorial = 'publicada' THEN
            RAISE EXCEPTION
                'Una versión publicada no se elimina; debe marcarse como reemplazada.';
        END IF;
        RETURN OLD;
    END IF;

    IF OLD.estado_editorial = 'publicada' THEN
        -- El contenido queda congelado. Solo se permite cerrar su vigencia,
        -- marcarla como reemplazada y reprogramar la revisión.
        IF (to_jsonb(NEW) - ARRAY[
                'estado_editorial', 'valido_hasta', 'proxima_revision_en'
            ]) IS DISTINCT FROM
           (to_jsonb(OLD) - ARRAY[
                'estado_editorial', 'valido_hasta', 'proxima_revision_en'
            ]) THEN
            RAISE EXCEPTION
                'El contenido publicado es inmutable. Cree una nueva versión editorial.';
        END IF;

        IF NEW.estado_editorial NOT IN ('publicada', 'reemplazada') THEN
            RAISE EXCEPTION
                'Una versión publicada solo puede pasar a reemplazada.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_version_publicada_inmutable
BEFORE UPDATE OR DELETE ON tramite_version
FOR EACH ROW EXECUTE FUNCTION proteger_version_publicada();

