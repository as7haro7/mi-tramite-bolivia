CREATE TABLE tramite_alias (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id      BIGINT NOT NULL REFERENCES tramite(id) ON DELETE CASCADE,
    alias           VARCHAR(200) NOT NULL,
    tipo            VARCHAR(20) NOT NULL DEFAULT 'popular'
                    CHECK (tipo IN ('popular', 'sigla', 'anterior', 'error_comun')),
    normalizado     VARCHAR(200) GENERATED ALWAYS AS
                    (public.normalizar_busqueda(alias)) STORED,
    UNIQUE (tramite_id, normalizado)
);

CREATE TABLE tramite_version (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_id              BIGINT NOT NULL REFERENCES tramite(id) ON DELETE CASCADE,
    numero_version          INTEGER NOT NULL CHECK (numero_version > 0),
    estado_editorial        VARCHAR(20) NOT NULL DEFAULT 'borrador'
                            CHECK (estado_editorial IN
                                  ('borrador', 'en_revision', 'publicada',
                                   'rechazada', 'reemplazada')),
    titulo                  VARCHAR(250) NOT NULL,
    resumen                 VARCHAR(700) NOT NULL,
    descripcion             TEXT NOT NULL,
    publico_objetivo        TEXT,
    resultado_esperado      TEXT,
    advertencias            TEXT,
    plazo_texto             VARCHAR(250),
    vigencia_resultado_texto VARCHAR(250),
    requiere_cita           BOOLEAN NOT NULL DEFAULT FALSE,
    url_inicio              TEXT,
    notas_internas          TEXT,
    valido_desde            TIMESTAMPTZ,
    valido_hasta            TIMESTAMPTZ,
    verificado_en           TIMESTAMPTZ,
    proxima_revision_en     TIMESTAMPTZ,
    creado_por              BIGINT,
    revisado_por            BIGINT,
    aprobado_por            BIGINT,
    creado_en               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    publicado_en            TIMESTAMPTZ,
    hash_contenido          VARCHAR(64),
    UNIQUE (tramite_id, numero_version),
    CHECK (valido_hasta IS NULL OR valido_desde IS NULL OR valido_hasta > valido_desde),
    CHECK (estado_editorial <> 'publicada'
           OR (publicado_en IS NOT NULL AND verificado_en IS NOT NULL))
);

-- Solo puede existir una versión publicada y vigente por trámite.
CREATE UNIQUE INDEX uq_tramite_una_version_publicada
    ON tramite_version (tramite_id)
    WHERE estado_editorial = 'publicada' AND valido_hasta IS NULL;

