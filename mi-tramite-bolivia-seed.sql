    con_cita        BOOLEAN NOT NULL DEFAULT FALSE,
    valido_desde    DATE,
    valido_hasta    DATE,
    CHECK (hora_cierre > hora_apertura),
    CHECK (valido_hasta IS NULL OR valido_desde IS NULL OR valido_hasta >= valido_desde)
