-- Normalización inmutable e independiente del esquema donde el proveedor
-- instale extensiones. Cubre los diacríticos usados habitualmente en español.
CREATE OR REPLACE FUNCTION public.normalizar_busqueda(valor TEXT)
RETURNS TEXT
LANGUAGE SQL
IMMUTABLE
PARALLEL SAFE
SET search_path TO public, extensions, pg_catalog
AS $$
    SELECT translate(
        lower(coalesce(valor, '')),
        'áéíóúüñ',
        'aeiouun'
    );
$$;

