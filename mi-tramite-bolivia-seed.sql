CREATE TABLE requisito_tramite (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tramite_version_id  BIGINT NOT NULL REFERENCES tramite_version(id) ON DELETE CASCADE,
    modalidad_id        BIGINT REFERENCES modalidad_tramite(id) ON DELETE CASCADE,
    codigo              VARCHAR(50) NOT NULL,
    titulo              VARCHAR(220) NOT NULL,
    descripcion         TEXT,
    obligatorio         BOOLEAN NOT NULL DEFAULT TRUE,
    cantidad_originales SMALLINT NOT NULL DEFAULT 0 CHECK (cantidad_originales >= 0),
    cantidad_copias     SMALLINT NOT NULL DEFAULT 0 CHECK (cantidad_copias >= 0),
    formato             VARCHAR(100),
    vigencia_documento  VARCHAR(180),
    emisor              VARCHAR(180),
    grupo_alternativa   VARCHAR(50),
    aplica_si           JSONB NOT NULL DEFAULT '{}'::jsonb,
    orden               SMALLINT NOT NULL DEFAULT 0,
    CHECK (jsonb_typeof(aplica_si) = 'object')
);

-- Un mismo requisito lógico puede tener una representación distinta por
-- modalidad (por ejemplo, documento PDF en línea y original presencial).
-- Los índices parciales también evitan duplicados en requisitos generales,
-- donde modalidad_id es NULL.
CREATE UNIQUE INDEX uq_requisito_general_codigo
    ON requisito_tramite(tramite_version_id, codigo)
    WHERE modalidad_id IS NULL;

CREATE UNIQUE INDEX uq_requisito_modalidad_codigo
    ON requisito_tramite(tramite_version_id, modalidad_id, codigo)
    WHERE modalidad_id IS NOT NULL;

CREATE TABLE paso_tramite (
